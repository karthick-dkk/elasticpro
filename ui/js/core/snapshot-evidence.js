/**
 * What is inside one snapshot, written down so it can be handed to an auditor.
 *
 * Pure: the dialog in ui/snapshot-dialogs.js gathers the facts (the listing row, the
 * snapshot detail when it could be read, who is signed in) and this turns them into the
 * three shapes they are shown in — the table on screen, the CSV and the plain-text block —
 * from ONE list of header fields and ONE list of rows, so the three cannot disagree.
 *
 * Nothing here computes a day span. The dates come from `dayOf` (parseIndexName, the one
 * reader of index names) and the covered range from `cover` (coveredDays, the definition
 * the snapshot rows already carry); this only lays them out.
 */

import { toCsv, csvEscape } from '../lib/fmt.js';
import { compareNullLast } from '../lib/sort-order.js';
import { spanDaysIso } from './volume.js';

export const NO_DATE = 'no date in name';

/**
 * The snapshot listing's card title. Before the repositories have been read there is no
 * repository to name, and "Snapshots in —" named one anyway.
 */
export function listingTitle(selected) {
  return selected ? `Snapshots in ${selected}` : 'Snapshots';
}

/**
 * What an empty listing says, in the order the facts are known: a search that matched
 * nothing, a cluster that could not be read, repositories not read yet, a cluster with no
 * repository, and only then a repository that is genuinely empty. "No snapshots in this
 * repository" was shown for all five, so an unreachable cluster read as a clean one.
 */
export function listingEmptyText({ searching = false, fetched = false, repos = [], error = '' } = {}) {
  if (searching) return 'No snapshot matches that search';
  if (error) return `Repositories could not be read: ${error}`;
  if (!fetched) return 'Repositories not read yet — press Refresh to list them';
  if (!repos.length) return 'No snapshot repositories on this cluster';
  return 'No snapshots in this repository';
}

/**
 * One row per index: its data day, and its shard outcome when the detail reported one.
 *
 * `failures` is the snapshot detail's list, or null when the detail could not be read —
 * then every row's status is unknown, never "ok": a snapshot we did not look inside has
 * not been shown to be clean.
 *
 * Sorted by data day (oldest first), then name; indices with no date in the name last.
 */
export function evidenceRows(names, dayOf, failures) {
  const byIndex = new Map();
  for (const f of failures || []) {
    const k = f && f.index;
    if (!k) continue;
    const cur = byIndex.get(k) || [];
    cur.push(f);
    byIndex.set(k, cur);
  }
  const rows = [...new Set(names || [])].map((index) => {
    const day = dayOf(index) || null;
    const fails = byIndex.get(index) || [];
    let status, detail = '';
    if (failures == null) status = 'unknown';
    else if (fails.length) {
      status = 'failed';
      detail = fails.map((f) => `shard ${f.shard_id ?? '?'}: ${f.reason || f.status || 'failed'}`).join('; ');
    } else status = 'ok';
    return { index, day, failedShards: fails.length, status, detail };
  });
  rows.sort((a, b) => {
    if (a.day !== b.day) {
      if (!a.day) return 1;
      if (!b.day) return -1;
      return a.day < b.day ? -1 : 1;
    }
    return a.index < b.index ? -1 : a.index > b.index ? 1 : 0;
  });
  return rows.map((r, i) => ({ n: i + 1, ...r }));
}

/**
 * "covers 2026-09-23 → 2026-09-29 (7 days, 0 missing days)", or why it cannot say.
 *
 * `cover` is coveredDays' shape; `named` false means the index names themselves are not
 * known, which is not the same as none of them carrying a date.
 */
export function coverLine(cover, { named = true } = {}) {
  if (!named) return 'covers unknown — the index names could not be read';
  if (!cover || !cover.coverFrom) return 'covers no dated days — no index name in this snapshot carries a date';
  const days = cover.coverDays === 1 ? '1 day' : `${cover.coverDays} days`;
  const miss = cover.missingDays === 1 ? '1 missing day' : `${cover.missingDays || 0} missing days`;
  return `covers ${cover.coverFrom} → ${cover.coverTo} (${days}, ${miss})`;
}

/**
 * The header block, as ordered {label, value} pairs. `value` is what is shown and copied;
 * `raw` (when present) is the machine-readable form the CSV carries instead — ISO times.
 *
 * Snapshot data only. The cluster's name and address and the "generated by <user>" stamp
 * used to lead this block; evidence gets pasted into tickets and sent to clients, and
 * neither an internal address nor an operator's account belongs there. The cluster is
 * named once, in the panel's subtitle, and the file name of an export.
 */
export function evidenceHeader(f) {
  const shards = f.shards || {};
  return [
    { key: 'repository', label: 'Repository', value: f.repository || '–' },
    { key: 'snapshot', label: 'Snapshot', value: f.snapshot || '–' },
    { key: 'state', label: 'State', value: f.state || 'unknown' },
    { key: 'taken', label: 'Taken', value: f.takenText || '–', raw: iso(f.taken) },
    { key: 'ended', label: 'Ended', value: f.endedText || '–', raw: iso(f.ended) },
    { key: 'duration', label: 'Duration', value: f.durationText || '–' },
    { key: 'shards', label: 'Shards',
      value: shards.total == null ? 'unknown'
        : `${shards.successful ?? 0} ok · ${shards.failed ?? 0} failed · ${shards.total} total` },
    { key: 'indices', label: 'Indices', value: f.indexCount == null ? 'unknown' : String(f.indexCount) },
    { key: 'covers', label: 'Data inside', value: f.cover || '–' },
  ];
}

/**
 * The orders the evidence table offers (lib/sort-order.js shape). The default is data
 * date, newest first: the question an auditor asks first is "how recent is the newest
 * data in here". Undated indices stay last whichever way the date order runs.
 */
export const EVIDENCE_SORTS = {
  index: { label: 'index name', dirs: { '1': 'A → Z', '-1': 'Z → A' }, start: 1 },
  day: { label: 'data date', dirs: { '-1': 'newest first', '1': 'oldest first' }, start: -1 },
  status: { label: 'shards', dirs: { '-1': 'failed first', '1': 'ok first' }, start: -1 },
};
export const DEFAULT_EVIDENCE_SORT = { key: 'day', dir: -1 };

const STATUS_RANK = { ok: 0, unknown: 1, failed: 2 };

/**
 * `evidenceRows` in the order shown, numbered again from 1 in that order — so the "#"
 * column, the CSV and the copied text count the way the screen does. Ties keep the
 * canonical order (data day, then name), so the result is stable.
 */
export function sortEvidenceRows(rows, sort = DEFAULT_EVIDENCE_SORT) {
  const dir = sort.dir === 1 ? 1 : -1;
  const by = {
    index: (a, b) => compareNullLast(a.index, b.index, dir),
    day: (a, b) => compareNullLast(a.day, b.day, dir),
    status: (a, b) => compareNullLast(STATUS_RANK[a.status] ?? 1, STATUS_RANK[b.status] ?? 1, dir),
  }[sort.key] || (() => 0);
  const out = [...(rows || [])].sort((a, b) => by(a, b) || (a.n - b.n));
  return out.map((r, i) => ({ ...r, n: i + 1 }));
}

function iso(ms) {
  const n = Number(ms);
  return ms && isFinite(n) && n > 0 ? new Date(n).toISOString() : '';
}

const statusText = (r) => (r.status === 'failed' ? `${r.failedShards} shard(s) failed` : r.status);

/** CSV: the header fields as leading `field,value` rows, a blank line, then the table. */
export function evidenceCsv(header, rows) {
  const head = header.map((f) => [f.label, f.raw !== undefined && f.raw !== '' ? f.raw : f.value]
    .map(csvEscape).join(',')).join('\n');
  const body = toCsv(rows.map((r) => ({
    '#': r.n, index: r.index, data_date: r.day || NO_DATE, shard_status: statusText(r), shard_detail: r.detail,
  })), ['#', 'index', 'data_date', 'shard_status', 'shard_detail']);
  return `${head}\n\n${body}\n`;
}

/** The plain-text block for pasting into a ticket: aligned header, then one line per index. */
export function evidenceText(header, rows) {
  const w = Math.max(...header.map((f) => f.label.length));
  const lines = ['SNAPSHOT EVIDENCE', ''];
  for (const f of header) lines.push(`${f.label.padEnd(w)}  ${f.value}`);
  lines.push('');
  const nw = String(rows.length).length;
  const iw = Math.max(5, ...rows.map((r) => r.index.length));
  const dw = Math.max(9, ...rows.map((r) => (r.day || NO_DATE).length));
  lines.push(`${'#'.padStart(nw)}  ${'Index'.padEnd(iw)}  ${'Data date'.padEnd(dw)}  Shards`);
  for (const r of rows) {
    lines.push(`${String(r.n).padStart(nw)}  ${r.index.padEnd(iw)}  ${(r.day || NO_DATE).padEnd(dw)}  ${statusText(r)}${r.detail ? ` — ${r.detail}` : ''}`);
  }
  if (!rows.length) lines.push('(no indices)');
  return lines.join('\n') + '\n';
}

/**
 * A cluster address fit for evidence: any user:password@ is removed. A URL can carry a
 * credential, and evidence gets pasted into tickets and audit folders. (The snapshot
 * evidence block no longer carries an address at all; this stays for anything that does.)
 */
export function safeUrl(u) {
  if (!u) return '';
  try {
    const x = new URL(String(u));
    x.username = ''; x.password = '';
    return x.toString().replace(/\/$/, '');
  } catch (_) {
    return String(u).replace(/\/\/[^/@]*@/, '//');
  }
}

/* ------------------------- the repositories overview ------------------------- */

/**
 * Across every snapshot in the repository, the span of log days they hold between them.
 *
 * Distinct from when the snapshots ran: this is what could actually be restored, read
 * from the dates in the index names each snapshot carries.
 */
export function recoverableRange(snaps) {
  let from = null, to = null;
  for (const s of snaps) {
    if (s.coverFrom && (from === null || s.coverFrom < from)) from = s.coverFrom;
    if (s.coverTo && (to === null || s.coverTo > to)) to = s.coverTo;
  }
  return { from, to, days: spanDaysIso(from, to) };
}

/**
 * One repository's row on the Repositories view, from the same figures the snapshot list
 * and the SLM table use. `snaps` is null until the listing has been read (unknown is not
 * zero), `newest` is the listing's first row (it arrives newest first), and `span` is
 * `recoverableRange` with `unknown` set when some rows came from `_cat` and name no indices.
 */
export function repoOverview(repo, snaps, policies = []) {
  const list = Array.isArray(snaps) ? snaps : null;
  const range = list ? recoverableRange(list) : { from: null, to: null, days: 0 };
  return {
    name: repo.name,
    count: list ? list.length : null,
    newest: list && list.length ? list[0] : null,
    span: { ...range, unknown: !!list && list.some((s) => s.indexNames == null) },
    policies: policies.filter((p) => p && p.policy && p.policy.repository === repo.name).map((p) => p.id),
  };
}

/** The repository to show open: the one asked for, only while it is still registered. */
export function openRepo(asked, repos) {
  return asked && (repos || []).some((r) => r.name === asked) ? asked : null;
}
