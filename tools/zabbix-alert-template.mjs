#!/usr/bin/env node
/**
 * Writes the Zabbix template for ElasticPro's alerts, from the rules Zabbix is meant to
 * raise (ui/js/core/zabbix-alerts.js) and their names (ui/js/core/alert-rules.js).
 *
 *   node tools/zabbix-alert-template.mjs > deploy/zabbix/template-elasticpro-alerts.yaml
 *
 * Per rule, two trapper items the scraper fills every run — the level (0 clear, 1 warning,
 * 2 critical, for graphs) and a one-line detail that starts with its level — and two
 * triggers on the detail, one per level. A rule that clears sends an empty detail, so its
 * problem resolves on the next run.
 */
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
globalThis.localStorage = globalThis.localStorage || { getItem: () => null, setItem() {}, removeItem() {} };
const { ZABBIX_ALERT_RULES } = await import(pathToFileURL(path.join(ROOT, 'ui/js/core/zabbix-alerts.js')).href);
const { ALERT_RULES } = await import(pathToFileURL(path.join(ROOT, 'ui/js/core/alert-rules.js')).href);

const T = 'ElasticPro alerts';
const uuid = (what) => {
  const h = crypto.createHash('sha256').update(`elasticpro-alerts/${what}`).digest('hex').slice(0, 32).split('');
  h[12] = '4';
  h[16] = '89ab'[parseInt(h[16], 16) % 4];
  return h.join('');
};
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rules = ZABBIX_ALERT_RULES.map((id) => ALERT_RULES.find((r) => r.id === id));

const lines = [];
const out = (s = '') => lines.push(s);
out('# Generated by tools/zabbix-alert-template.mjs — do not edit by hand.');
out('zabbix_export:');
out("  version: '7.0'");
out('  template_groups:');
out(`    - uuid: ${uuid('group')}`);
out('      name: Templates/Applications');
out('  templates:');
out(`    - uuid: ${uuid('template')}`);
out(`      template: ${q(T)}`);
out(`      name: ${q(T)}`);
out(`      description: ${q('ElasticPro alert rules the Elasticsearch cluster template does not cover, raised as Zabbix problems. Filled by tools/elasticpro-scrape.mjs --send. Link to cluster hosts.')}`);
out('      vendor:');
out('        name: ElasticPro');
out("        version: 7.0-1");
out('      groups:');
out('        - name: Templates/Applications');
out('      items:');
for (const r of rules) {
  out(`        - uuid: ${uuid(`level/${r.id}`)}`);
  out(`          name: ${q(`Alert: ${r.label}`)}`);
  out('          type: TRAP');
  out(`          key: ${q(`elasticpro.alert[${r.id}]`)}`);
  out('          value_type: UNSIGNED');
  out(`          description: ${q(`${r.why} 0 clear, 1 warning, 2 critical.`)}`);
  out('          valuemap:');
  out("            name: 'ElasticPro alert level'");
  out('          tags:');
  out('            - tag: component');
  out('              value: elasticpro-alert');
  out('            - tag: rule');
  out(`              value: ${q(r.id)}`);
  out(`        - uuid: ${uuid(`detail/${r.id}`)}`);
  out(`          name: ${q(`Alert detail: ${r.label}`)}`);
  out('          type: TRAP');
  out(`          key: ${q(`elasticpro.alert.detail[${r.id}]`)}`);
  out('          value_type: TEXT');
  out("          trends: '0'");
  out('          tags:');
  out('            - tag: component');
  out('              value: elasticpro-alert');
}
out('      valuemaps:');
out(`        - uuid: ${uuid('valuemap')}`);
out("          name: 'ElasticPro alert level'");
out('          mappings:');
out("            - value: '0'");
out('              newvalue: clear');
out("            - value: '1'");
out('              newvalue: warning');
out("            - value: '2'");
out('              newvalue: critical');
out('  triggers:');
for (const r of rules) {
  for (const [lvl, prio, word] of [[2, 'HIGH', 'critical'], [1, 'WARNING', 'warning']]) {
    // One item decides both the severity and the text: the detail, which starts with its
    // level. Reading a separate level item raced the text — see zabbixAlertValues().
    out(`    - uuid: ${uuid(`trigger/${r.id}/${lvl}`)}`);
    out(`      expression: ${q(`find(/${T}/elasticpro.alert.detail[${r.id}],,"regexp","^${word}: ")=1`)}`);
    out(`      name: ${q(`${r.label} — {ITEM.LASTVALUE1}`)}`);
    out(`      event_name: ${q(`${r.label} — {ITEM.LASTVALUE1}`)}`);
    out(`      priority: ${prio}`);
    // Closable by hand: an operator who has dealt with it can say so, and if it is still
    // true the next scraper run opens it again, freshly named.
    out('      manual_close: YES');
    out(`      description: ${q(`${r.why} Raised by ElasticPro (${word}).`)}`);
    out('      tags:');
    out('        - tag: source');
    out('          value: elasticpro');
    out('        - tag: rule');
    out(`          value: ${q(r.id)}`);
  }
}
process.stdout.write(`${lines.join('\n')}\n`);
