#!/usr/bin/env node
/**
 * Writes the Zabbix template for ElasticPro's log-delay measurements, from DELAY_ITEMS.
 *
 *   node tools/zabbix-delay-template.mjs > deploy/zabbix/template-elasticpro-log-delay.yaml
 *
 * One trapper item per measured figure on each cluster host, keyed elasticpro.delay[<key>], filled
 * by tools/elasticpro-scrape.mjs --send each time it measures (every 15 minutes by default).
 * Metrics only: the alarm for late devices is the "log-delay" rule in the alerts template,
 * and the hourly, daily and change figures are worked out where they are shown — on the
 * client's master host.
 */
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
globalThis.localStorage = globalThis.localStorage || { getItem: () => null, setItem() {}, removeItem() {} };
const { DELAY_ITEMS } = await import(pathToFileURL(path.join(ROOT, 'ui/js/core/log-delay.js')).href);

const T = 'ElasticPro log delay';
const uuid = (what) => {
  const h = crypto.createHash('sha256').update(`elasticpro-log-delay/${what}`).digest('hex').slice(0, 32).split('');
  h[12] = '4';
  h[16] = '89ab'[parseInt(h[16], 16) % 4];
  return h.join('');
};
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const lines = [];
const out = (s = '') => lines.push(s);
const item = ({ id, name, key, type, units, description }) => {
  out(`        - uuid: ${uuid(`item/${id}`)}`);
  out(`          name: ${q(name)}`);
  out('          type: TRAP');
  out(`          key: ${q(key)}`);
  out(`          value_type: ${type}`);
  if (type === 'TEXT') out("          trends: '0'");
  if (units) out(`          units: ${q(units)}`);
  if (description) out(`          description: ${q(description)}`);
  out('          tags:');
  out('            - tag: component');
  out('              value: log-delay');
};

out('# Generated by tools/zabbix-delay-template.mjs — do not edit by hand.');
out('zabbix_export:');
out("  version: '7.0'");
out('  templates:');
out(`    - uuid: ${uuid('template')}`);
out(`      template: ${q(T)}`);
out(`      name: ${q(T)}`);
out(`      description: ${q('Log delay as ElasticPro measures it: devices late, how late. Filled by tools/elasticpro-scrape.mjs --send every time it measures. Link to cluster hosts.')}`);
out('      vendor:');
out('        name: ElasticPro');
out('        version: 7.0-1');
out('      groups:');
out('        - name: Templates/Applications');
out('      items:');
for (const d of DELAY_ITEMS) {
  item({ id: d.key, name: `Log delay: ${d.label}`, key: `elasticpro.delay[${d.key}]`,
         type: d.units === 's' ? 'FLOAT' : 'UNSIGNED', units: d.units });
}
item({ id: 'worst_device', name: 'Log delay: Worst device', key: 'elasticpro.delay[worst_device]', type: 'TEXT',
       description: 'The device furthest behind at the last measurement.' });
process.stdout.write(`${lines.join('\n')}\n`);
