#!/usr/bin/env node
/**
 * Writes the Zabbix template for the client storage plan, from CLIENT_COLUMNS.
 *
 *   node tools/zabbix-plan-template.mjs > deploy/zabbix/template-elasticpro-client-plan.yaml
 *
 * Generated rather than written by hand so the template cannot disagree with the Volume
 * report: one item per client-plan column on each cluster host, named with the column's
 * label, keyed elasticpro.plan[<column key>], typed from its `kind`. Add a column to the plan and regenerate;
 * the unit test fails if the committed file is out of date.
 *
 * UUIDs are derived from what they identify, so regenerating changes nothing Zabbix
 * already has — an import updates in place rather than duplicating.
 */
import crypto from 'node:crypto';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { CLIENT_COLUMNS } = await import(pathToFileURL(path.join(ROOT, 'ui/js/core/volume.js')).href);

const T = 'ElasticPro client plan';
const uuid = (what) => {
  const h = crypto.createHash('sha256').update(`elasticpro-client-plan/${what}`).digest('hex').slice(0, 32).split('');
  h[12] = '4';                                   // shaped as a v4 UUID, as Zabbix expects
  h[16] = '89ab'[parseInt(h[16], 16) % 4];
  return h.join('');
};
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

// Units: "!" stops Zabbix putting K/M/G in front — 1500 GB must not become "1.5 KGB".
const units = (c) => (c.unit === 'GB' ? '!GB' : c.unit === 'days' ? '!days' : c.unit || '');
const valueType = (c) => (c.kind === 'num' ? 'FLOAT' : 'CHAR');

const cols = CLIENT_COLUMNS.filter((c) => c.key !== 'name');   // the host is the client
const key = (k) => `elasticpro.plan[${k}]`;
const ref = (k) => `/${T}/${key(k)}`;

const lines = [];
const out = (s = '') => lines.push(s);
// `plan` is the column's section (Live storage, Backup storage…) and `column` its place in
// the Client plan grid. The Volume report widget in Zabbix reads both from the items, so it
// lays the plan out as the page does without keeping a column list of its own.
const tags = (group, order) => {
  out('          tags:');
  if (order !== undefined) { out('            - tag: column'); out(`              value: '${String(order).padStart(2, '0')}'`); }
  out('            - tag: component');
  out('              value: client-plan');
  if (group) { out('            - tag: plan'); out(`              value: ${q(group)}`); }
};
out('# Generated by tools/zabbix-plan-template.mjs from CLIENT_COLUMNS — do not edit by hand.');
out('zabbix_export:');
out("  version: '7.0'");
out('  template_groups:');
out(`    - uuid: ${uuid('group')}`);
out('      name: Templates/Applications');
out('  templates:');
out(`    - uuid: ${uuid('template')}`);
out(`      template: ${q(T)}`);
out(`      name: ${q(T)}`);
out(`      description: ${q('The Volume report\'s Client plan for the cluster this host is, pushed by tools/elasticpro-scrape.mjs --send. Link it to cluster hosts (or into the cluster template). Values Elasticsearch cannot give are not sent: a gap is "unknown", never zero.')}`);
out('      vendor:');
out('        name: ElasticPro');
out("        version: 7.0-2");
out('      groups:');
out('        - name: Templates/Applications');
out('      items:');
out(`        - uuid: ${uuid('epoch')}`);
out(`          name: ${q('Client plan: last update')}`);
out('          type: TRAP');
out('          key: elasticpro.plan.epoch');
out('          value_type: UNSIGNED');
out('          units: unixtime');
out(`          description: ${q('When the scraper last pushed the plan. A scraper that stopped looks like a steady fleet otherwise.')}`);
tags();
out('          triggers:');
out(`            - uuid: ${uuid('stale')}`);
out(`              expression: ${q(`nodata(/${T}/elasticpro.plan.epoch,{$ELASTICPRO.PLAN.STALE})=1`)}`);
out(`              name: ${q('Client plan: no update for {$ELASTICPRO.PLAN.STALE} — every figure is old')}`);
out('              priority: WARNING');
out(`        - uuid: ${uuid('reachable')}`);
out(`          name: ${q('Client plan: cluster reachable')}`);
out('          type: TRAP');
out('          key: elasticpro.plan.reachable');
out('          value_type: UNSIGNED');
tags();
out('          triggers:');
out(`            - uuid: ${uuid('trigger/unreachable')}`);
out(`              expression: ${q(`last(/${T}/elasticpro.plan.reachable)=0`)}`);
out(`              name: ${q('Client plan: cluster unreachable — the plan cannot be measured')}`);
out('              priority: AVERAGE');
for (const c of cols) {
  out(`        - uuid: ${uuid(`item/${c.key}`)}`);
  out(`          name: ${q(`Client plan: ${c.label}`)}`);
  out('          type: TRAP');
  out(`          key: ${q(key(c.key))}`);
  out(`          value_type: ${valueType(c)}`);
  if (units(c)) out(`          units: ${q(units(c))}`);
  if (valueType(c) === 'CHAR') out("          trends: '0'");
  if (c.help) out(`          description: ${q(c.help)}`);
  tags(c.group, cols.indexOf(c) + 1);
}
out('      tags:');
out('        - tag: class');
out('          value: software');
out('        - tag: target');
out('          value: elasticsearch');
out('      macros:');
out("        - macro: '{$ELASTICPRO.PLAN.LIVE_DAYS.MIN}'");
out("          value: '14'");
out(`          description: ${q('Warn when live storage fills in fewer days than this.')}`);
out("        - macro: '{$ELASTICPRO.PLAN.LIVE_USED.WARN}'");
out("          value: '85'");
out(`          description: ${q('Warn when live storage is more than this percent used.')}`);
out("        - macro: '{$ELASTICPRO.PLAN.STALE}'");
out("          value: '30m'");
out(`          description: ${q('Complain when the scraper has not pushed for this long.')}`);
// Triggers and graphs over more than one item live at the root of an export, not under
// the template — Zabbix's format, not a choice.
out('  triggers:');
const trig = (id, expr, name, prio) => {
  out(`    - uuid: ${uuid(`trigger/${id}`)}`);
  out(`      expression: ${q(expr)}`);
  out(`      name: ${q(name)}`);
  out(`      priority: ${prio}`);
};
trig('live-used', `last(${ref('live.used.pct')})>{$ELASTICPRO.PLAN.LIVE_USED.WARN}`,
  'Client plan: live storage over {$ELASTICPRO.PLAN.LIVE_USED.WARN}% used', 'WARNING');
trig('live-days', `last(${ref('live.days')})<{$ELASTICPRO.PLAN.LIVE_DAYS.MIN}`,
  'Client plan: live storage fills in under {$ELASTICPRO.PLAN.LIVE_DAYS.MIN} days at the current rate', 'HIGH');
trig('live-30d', `last(${ref('live.total')})<last(${ref('live.required.30d')})`,
  'Client plan: not enough live storage for 30 days of indices', 'WARNING');
trig('backup-365d', `last(${ref('backup.total')})<last(${ref('backup.required.365d')})`,
  'Client plan: backup storage below what 365 days of snapshots needs', 'INFO');
out('  graphs:');
const graph = (id, name, keys) => {
  out(`    - uuid: ${uuid(`graph/${id}`)}`);
  out(`      name: ${q(`Client plan: ${name}`)}`);
  out('      graph_items:');
  const colors = ['1A7C11', 'F63100', '2774A4', 'A54F10', 'FC6EA3'];
  keys.forEach((k, i) => {
    out(`        - sortorder: '${i}'`);
    out(`          color: ${colors[i % colors.length]}`);
    out('          item:');
    out(`            host: ${q(T)}`);
    out(`            key: ${q(key(k))}`);
  });
};
graph('volume', 'volume per day', ['volume.day', 'volume.day.buffered']);
graph('live', 'live storage against need', ['live.total', 'live.required.30d', 'live.required.90d']);
graph('days', 'days of storage left', ['live.days', 'backup.days']);
process.stdout.write(`${lines.join('\n')}\n`);
